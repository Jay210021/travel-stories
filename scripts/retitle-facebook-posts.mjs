function clean(value) {
  return value
    .replace(/https?:\/\/\S+/g, "")
    .replace(/#[^\s#]+/g, "")
    .replace(/[\p{Extended_Pictographic}\p{Regional_Indicator}\p{Emoji_Modifier}\uFE0F\u200D]/gu, "")
    .replace(/[「」“”‘’]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function excerpt(value, limit = 30) {
  const text = clean(value)
    .replace(/^[/／\-–—]+/, "")
    .split(/[。！？!?；;]|\s[-–—]\s/)[0]
    .trim();
  if (text.length <= limit) return text;
  const shortened = text.slice(0, limit);
  const boundary = Math.max(shortened.lastIndexOf("，"), shortened.lastIndexOf("、"), shortened.lastIndexOf(" "));
  return `${(boundary >= 12 ? shortened.slice(0, boundary) : shortened).trim()}…`;
}

function titleFromBody(body, index) {
  if (!body?.trim()) return `待確認：Facebook 連結貼文 ${index}`;

  const normalized = body.trim();
  const bracketed = normalized.match(/^\s*[\/／《〔【]([^\/／》〕】\n]{2,40})[\/／》〕】]\s*/);
  if (bracketed) {
    const topic = clean(bracketed[1]);
    const rest = excerpt(normalized.slice(bracketed[0].length), 24);
    if (genericTopics.has(topic) && rest) return `${topic}：${rest}`;
    return topic;
  }

  const day = clean(normalized).match(/^(.{2,14}?\s*Day\s*\d+)\s*(.*)$/i);
  if (day) {
    const subject = day[1].replace(/\s*Day\s*/i, " Day ");
    const detail = excerpt(day[2], 22);
    return detail ? `${subject}：${detail}` : subject;
  }

  return excerpt(normalized, 34) || `待確認：未命名貼文 ${index}`;
}

function makeUnique(title, used) {
  const count = (used.get(title) ?? 0) + 1;
  used.set(title, count);
  return count === 1 ? title : `${title}（${count}）`;
}

for (const relativeFile of files) {
  const file = path.resolve(relativeFile);
  const json = JSON.parse(fs.readFileSync(file, "utf8"));
  const key = json.drafts ? "drafts" : "posts";
  const used = new Map();
  let emptyIndex = 0;

  json[key] = json[key].map((post) => {
    if (!(post.body ?? post.text)?.trim()) emptyIndex += 1;
    const id = post.draftId ?? post.importId;
    const title = makeUnique(overrides[id] ?? titleFromBody(post.body ?? post.text ?? "", emptyIndex), used);
    return { ...post, title };
  });

  fs.writeFileSync(file, `${JSON.stringify(json, null, 2)}\n`, "utf8");
  console.log(`Updated ${json[key].length} titles in ${relativeFile}`);
}

